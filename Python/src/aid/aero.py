def _cosd(deg: float) -> float:
    return math.cos(math.radians(float(deg)))


def _tand(deg: float) -> float:
    return math.tan(math.radians(float(deg)))


def _as_vec(value) -> np.ndarray:
    return np.atleast_1d(np.asarray(value, dtype=float)).reshape(-1).astype(float, copy=True)


def _store_vec(pt: dict, key: str, values: np.ndarray) -> None:
    raw = pt[key]
    if isinstance(raw, list):
        raw[:] = [float(v) for v in values]
        return
    if isinstance(raw, np.ndarray) and raw.shape == values.shape:
        raw[...] = values
        return
    if values.size == 1 and not isinstance(raw, (list, np.ndarray)):
        pt[key] = float(values[0])
        return
    pt[key] = values


def _interp(x, y, xq: float, method: str) -> float:
    xv = np.asarray(x, dtype=float).reshape(-1)
    yv = np.asarray(y, dtype=float).reshape(-1)
    if xv.size != yv.size:
        raise ValueError(f"interp length {xv.size} != {yv.size}")
    if xv.size >= 2 and xv[0] > xv[-1]:
        xv = xv[::-1]
        yv = yv[::-1]
    query = float(xq)
    if method == "spline":
        return float(CubicSpline(xv, yv, extrapolate=True)(query))
    if method == "linear":
        fn = interp1d(
            xv,
            yv,
            kind="linear",
            bounds_error=False,
            fill_value="extrapolate",
            assume_sorted=True,
        )
        return float(fn(query))
    if method == "pchip":
        return float(PchipInterpolator(xv, yv, extrapolate=True)(query))
    raise ValueError(method)


def _nested(x_inner, x_mid, x_outer, table, q_inner: float, q_mid: float, q_outer: float) -> float:
    """Sweep (spline), then aspect ratio (linear), then taper (spline)."""
    outer = []
    for band in table:
        mid = [_interp(x_inner, row, q_inner, "spline") for row in band]
        outer.append(_interp(x_mid, mid, q_mid, "linear"))
    return _interp(x_outer, outer, q_outer, "spline")


def _select_xac_table(mach: float, sweep_le: float):
    """Aero.m lines 461-480. Both branches run when Mach is exactly 1."""
    table = None
    x0 = None
    if mach <= 1.0:
        disc = 1.0 - mach * mach
        beta = math.sqrt(disc) if disc > 0.0 else 0.0
        if beta == 0.0:
            x0 = 1.0
            table = _XAC_Y2
        else:
            x0 = _tand(sweep_le) / beta
            if x0 > 0.0 or x0 <= 1.0:
                table = _XAC_Y1
            if x0 > 1.0:
                x0 = 1.0 / x0
                table = _XAC_Y2
    if mach >= 1.0:
        disc = mach * mach - 1.0
        beta = math.sqrt(disc) if disc > 0.0 else 0.0
        if beta == 0.0:
            x0 = 1.0
            table = _XAC_Y3
        else:
            x0 = _tand(sweep_le) / beta
            if x0 > 0.0 or x0 <= 1.0:
                table = _XAC_Y4
            if x0 > 1.0:
                x0 = 1.0 / x0
                table = _XAC_Y3
    if table is None or x0 is None:
        raise ValueError(f"aerodynamic center table is undefined at Mach {mach}")
    return table, x0


def aero(pt: dict, mach: float, angl: bool) -> dict:
    """Mutates pt. Sets a (scalar, after the MATLAB pi/180 scale), alpha0L (scalar degrees),
    Cm (scalar), x_ac (MATLAB line 494). Copies Aero.m lines 1-497 except the Propeller block.
    swp row k in MATLAB is pt['swp'][k-1, -1]."""
    mach = float(mach)
    a0 = _as_vec(pt["a0"])
    for i, value in enumerate(a0):
        if value < 1.0:
            a0[i] = value * 180.0 / math.pi
    _store_vec(pt, "a0", a0)
    a0_mean = (float(a0[0]) + float(a0[-1])) / 2.0

    k = a0_mean / (2.0 * math.pi)
    ar = _as_vec(pt["AR"])
    # Local AR parameter uses aspect ratio before the dihedral correction.
    ar_before_angl = float(ar[-1])
    if angl:
        if float(pt["SSPNOP"]) != 0.0:
            ar[-1] = ar[-1] * (
                float(pt["SSPNOP"]) * _cosd(pt["DHDADI"])
                + (float(pt["SSPN"]) - float(pt["SSPNOP"])) * _cosd(pt["DHDADO"])
            ) / float(pt["SSPN"])
        else:
            ar[-1] = ar[-1] * _cosd(pt["DHDADI"])
    _store_vec(pt, "AR", ar)

    swp = np.asarray(pt["swp"], dtype=float)
    sweep_le = float(swp[0, -1])
    sweep_c4 = float(swp[1, -1])
    sweep_c2 = float(swp[2, -1])
    if mach < 1.0:
        beta = math.sqrt(1.0 - mach * mach)
        ar_param = beta * ar_before_angl / k
        tan_term = _tand(sweep_c2) / beta
        pt["a"] = (
            2.0
            * math.pi
            * float(ar[-1])
            / (2.0 + math.sqrt(ar_param**2 * (1.0 + tan_term**2) + 4.0))
        )
    else:
        # sqrt(1-M^2) is 0 at Mach 1 and imaginary above it. MATLAB's lift
        # slope is non-finite there, and execution still reaches x_ac.
        pt["a"] = math.nan

    tr = _as_vec(pt["TR"])
    tr[-1] = float(np.real(tr[-1]))
    _store_vec(pt, "TR", tr)
    taper = float(tr[-1])
    aspect = float(ar[-1])

    aol_theta = _nested(_AOL_SWEEP, _AOL_AR, _AOL_TAPER, _AOL_Y, sweep_c4, aspect, taper)
    mcs4 = mach * _cosd(sweep_c4)
    aol_curves = [_interp(_AOL_MCS, row, mcs4, "pchip") for row in _AOL_MY]
    aol_theta_m = _interp(_AOL_TC, aol_curves, float(pt["TC"]), "linear")
    alpha0 = _as_vec(pt["alpha0"])
    twist = float(pt["TWISTA"])
    alpha0l = (alpha0 + aol_theta * twist) * aol_theta_m
    pt["alpha0L"] = float((alpha0l[0] + alpha0l[-1]) / 2.0)

    dcm_theta = _nested(_DCM_SWEEP, _DCM_AR, _DCM_TAPER, _DCM_Y, sweep_c4, aspect, taper)
    dcm_theta_m = _interp(_DCM_MACH, _DCM_MY, mach, "spline")
    cos_c4 = _cosd(sweep_c4)
    cm_ac = _as_vec(pt["Cm_ac"])
    cm = cm_ac * aspect * cos_c4**2 / (aspect + 2.0 * cos_c4)
    cm = (cm + dcm_theta * twist) * dcm_theta_m
    pt["Cm"] = float((cm[0] + cm[-1]) / 2.0)

    at = aspect * _tand(sweep_le)
    table, x0 = _select_xac_table(mach, sweep_le)
    xac_cr = _nested(_XAC_BETA, _XAC_AR, _XAC_TAPER, table, x0, at, taper)
    cbar = float(_as_vec(pt["cbar"])[-1])
    pt["x_ac"] = (xac_cr * float(pt["CHRDR"]) - float(pt["xmac"])) / cbar

    pt["a"] = pt["a"] * math.pi / 180.0
    return pt
