_ALT_MAX = 21336.0


def _ssl() -> dict[str, float]:
    return {"rho": RHO_SSL, "a": 340.3, "p": P_SSL, "mu": MU_SSL}


def isa_atmosphere(alt: float) -> dict[str, float]:
    """Return Tornado ISA properties at altitude *alt* (meters)."""
    altitude = float(alt)
    if altitude < 0.0 or altitude >= _ALT_MAX:
        return _ssl()

    alt_col = _ISA_TABLE[:, 0]
    i = int(np.searchsorted(alt_col, altitude, side="right") - 1)
    j = i + 1
    if j >= len(_ISA_TABLE):
        return _ssl()

    d_a = alt_col[j] - alt_col[i]
    da = altitude - alt_col[i]
    row_i = _ISA_TABLE[i]
    row_j = _ISA_TABLE[j]

    p_ratio = row_i[3] + da * (row_j[3] - row_i[3]) / d_a
    rho_ratio = row_i[4] + da * (row_j[4] - row_i[4]) / d_a
    mu_ratio = row_i[5] + da * (row_j[5] - row_i[5]) / d_a
    a = row_i[7] + da * (row_j[7] - row_i[7]) / d_a

    return {
        "rho": rho_ratio * RHO_SSL,
        "a": a,
        "p": p_ratio * P_SSL,
        "mu": mu_ratio * MU_SSL,
    }
